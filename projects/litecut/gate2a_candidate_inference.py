def upgrade_legacy_student_state_dict(state_dict: dict[str, torch.Tensor]) -> dict[str, torch.Tensor]:
    """Match the canonical loader's compatibility translation for old names."""
    upgraded: dict[str, torch.Tensor] = {}
    for key, value in state_dict.items():
        new_key = key
        for old, new in (("group1_encoder.", "group_encoders.0."),
                         ("group2_encoder.", "group_encoders.1."),
                         ("group3_encoder.", "group_encoders.2.")):
            if new_key.startswith(old):
                new_key = new + new_key[len(old):]
                break
        new_key = re.sub(r"^experts\.(\d+)\.0\.", r"experts.\1.head.0.", new_key)
        new_key = re.sub(r"^experts\.(\d+)\.2\.", r"experts.\1.head.2.", new_key)
        # A legacy checkpoint may have carried a teacher alignment adapter;
        # teacher_hidden_dim=None in the inference-only Student has Identity.
        if new_key.startswith("teacher_align_adapter."):
            continue
        upgraded[new_key] = value
    return upgraded


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def parse_aiger_ascii_binary(path: Path) -> tuple[dict[int, list[tuple[int, int]]], int, int, int, int]:
    """Read an AIGER ``aig`` file and return direct AIG adjacency.

    The canonical extractor's ``feat_graph`` omits PO objects and represents a
    complemented AIG edge as ``edge_type=1``.  AIGER's binary AND section is
    delta encoded; PI/PO sections remain ASCII.
    """
    data = path.read_bytes()
    nl = data.find(b"\n")
    if nl < 0:
        raise ValueError(f"Missing AIGER header in {path}")
    header = data[:nl].decode("ascii").split()
    if len(header) != 6 or header[0] != "aig":
        raise ValueError(f"Expected binary AIGER 'aig' header, got {header}")
    max_var, n_pi, n_latch, n_po, n_and = map(int, header[1:])
    pos = nl + 1
    # Binary AIGER has implicit PIs (unlike ASCII ``aag``); only latch lines
    # are present before the PO literals.
    for _ in range(n_latch):
        end = data.find(b"\n", pos)
        if end < 0:
            raise ValueError("Truncated AIGER PI/latch section")
        pos = end + 1
    # PO literals are not part of feat_graph, but must be skipped.
    for _ in range(n_po):
        end = data.find(b"\n", pos)
        if end < 0:
            raise ValueError("Truncated AIGER PO section")
        pos = end + 1

    def varint() -> int:
        nonlocal pos
        value = 0
        shift = 0
        while True:
            if pos >= len(data):
                raise ValueError("Truncated AIGER varint")
            byte = data[pos]
            pos += 1
            value |= (byte & 0x7F) << shift
            if byte < 0x80:
                return value
            shift += 7
            if shift > 35:
                raise ValueError("Invalid AIGER varint")

    graph: dict[int, list[tuple[int, int]]] = {i: [] for i in range(max_var + 1)}
    for i in range(n_and):
        lhs = 2 * (n_pi + n_latch + i + 1)
        delta0 = varint()
        delta1 = varint()
        rhs0 = lhs - delta0
        rhs1 = rhs0 - delta1
        for lit in (rhs0, rhs1):
            src = lit // 2
            comp = lit & 1
            graph.setdefault(src, []).append((lhs // 2, comp))
        graph.setdefault(lhs // 2, [])
    return graph, max_var, n_pi, n_po, n_and


def parse_library(path: Path) -> dict[str, Any]:
    text = path.read_text(encoding="utf-8")
    match = re.search(r"LIBRARY\[\] = \{(.*?)\};", text, re.S)
    if not match:
        raise ValueError(f"LIBRARY array not found in {path}")
    values = [int(x.strip()) for x in match.group(1).split(",") if x.strip()]
    cur = 0
    p_phases = values[cur:cur + 65536]; cur += 65536
    p_perms = values[cur:cur + 65536]; cur += 65536
    perms4 = [values[cur + 4 * i:cur + 4 * (i + 1)] for i in range(24)]; cur += 96
    p_map = values[cur:cur + 65536]; cur += 65536
    n_nodes = values[cur:cur + 222]; cur += 222
    n_subgraphs = values[cur:cur + 222]; cur += 222
    classes: dict[int, dict[str, Any]] = {}
    for cls in range(222):
        fanins = []
        for _ in range(n_nodes[cls]):
            fanins.append(tuple(values[cur:cur + 4]))
            cur += 4
        roots = values[cur:cur + n_subgraphs[cls]]
        cur += n_subgraphs[cls]
        classes[cls] = {"fanins": fanins, "roots": roots}
    if cur != len(values):
        raise ValueError(f"Library parse ended at {cur}, expected {len(values)}")
    return {"p_phases": p_phases, "p_perms": p_perms, "perms4": perms4,
            "p_map": p_map, "classes": classes}


def materialize_candidate_subgraph(record: dict[str, Any], lib: dict[str, Any], synthetic_base: int = 10_000_000) -> tuple[dict[int, list[tuple[int, int]]], dict[str, Any]]:
    """Rebuild the exact library replacement DAG for one Gate1 record.

    The preserved Gate1 root wrapper keeps its original ID.  Other internal
    library vertices receive deterministic synthetic IDs, while cut leaves use
    the recorded AIG IDs.  Edge complements follow BuildSubgr semantics:
    ``library_isC XOR uPhase(input_index)``.
    """
    root = int(record.get("target_root", record.get("root")))
    leaves = [int(x) for x in record["cut_leaves"]]
    if len(leaves) == 3:
        leaves.append(0)  # BuildSubgr pads 3-leaf cuts with the constant node.
    if len(leaves) != 4:
        raise ValueError(f"Gate1 replacement requires 3 or 4 leaves, got {leaves}")
    cls = int(record["truth_class"])
    sub_idx = int(record["subgraph_index"])
    phase = int(record["phase"])
    perm = [int(x) for x in record["permutation"]]
    if len(perm) != 4:
        raise ValueError(f"Expected four permutation entries, got {perm}")
    cdata = lib["classes"][cls]
    roots = cdata["roots"]
    if sub_idx < 0 or sub_idx >= len(roots):
        raise ValueError(f"subgraph_index={sub_idx} outside class {cls} roots={roots}")
    rt = int(roots[sub_idx])
    fanins = cdata["fanins"]

    # BuildSubgr's match[0..3] = cut.leaves[pPerm[0..3]].
    matched_leaves = [leaves[perm[i]] for i in range(4)]
    is_c_input = [(phase >> i) & 1 for i in range(4)]
    used: set[int] = set()

    def collect(v: int) -> None:
        if v < 4 or v in used:
            return
        used.add(v)
        a, b, _, _ = fanins[v - 4]
        collect(int(a)); collect(int(b))
    collect(rt)

    # Root wrapper is the actual Gate1 root ID; internal vertices are stable
    # synthetic IDs so they cannot collide with original AIG IDs.
    mapping: dict[int, int] = {i: matched_leaves[i] for i in range(4)}
    for v in sorted(used):
        mapping[v] = root if v == rt else synthetic_base + (v - 4)

    subg: dict[int, list[tuple[int, int]]] = {}
    for v in sorted(used):
        a, b, ca, cb = fanins[v - 4]
        # Internal inputs have no uPhase bit; only 0..3 are complemented by
        # the cut truth phase, exactly as in rewrite.cu BuildSubgr.
        ea = int(ca) ^ (is_c_input[a] if a < 4 else 0)
        eb = int(cb) ^ (is_c_input[b] if b < 4 else 0)
        node = mapping[v]
        subg.setdefault(mapping[a], []).append((node, ea))
        subg.setdefault(mapping[b], []).append((node, eb))
        subg.setdefault(node, [])
    # Do not add padded/unused cut inputs as isolated vertices.  The canonical
    # ``construct_subg_of_cut`` emits vertices that participate in the
    # replacement cone; an isolated constant introduced solely by the 3-leaf
    # padding convention is not part of that subgraph.

    info = {
        "library_class": cls,
        "library_subgraph_root": rt,
        "matched_library_inputs": matched_leaves,
        "used_library_nodes": sorted(used),
        "vertex_mapping": {str(k): int(v) for k, v in mapping.items()},
        "synthetic_internal_ids": sorted(v for k, v in mapping.items() if k >= 4 and k != rt),
    }
    return subg, info


def extract_replay_cone_subgraph(aig_graph: dict[int, list[tuple[int, int]]], record: dict[str, Any], n_pi: int) -> tuple[dict[int, list[tuple[int, int]]], dict[str, Any]]:
    """Extract a full-correspondence/no-op cone from its Gate1 replay AIG.

    A full-correspondence candidate has no newly allocated library nodes; its
    materialized replacement is the existing replay graph.  When the replay
    AIG is available, using that graph preserves the exact current
    implementation instead of inventing a second abstract DAG.
    """
    root = int(record.get("target_root", record.get("root")))
    cut = {int(x) for x in record["cut_leaves"]}
    preds: dict[int, list[tuple[int, int]]] = {}
    for u, edges in aig_graph.items():
        for v, edge_type in edges:
            preds.setdefault(v, []).append((u, edge_type))
    seen: set[int] = set()
    stack = [root]
    while stack:
        node = stack.pop()
        if node in seen or node in cut or node == 0:
            continue
        seen.add(node)
        for pred, _ in preds.get(node, []):
            if pred not in seen and pred not in cut and pred != 0:
                stack.append(pred)
    subg: dict[int, list[tuple[int, int]]] = {n: [] for n in seen}
    for node in seen:
        for pred, edge_type in preds.get(node, []):
            if pred in seen or pred in cut or pred == 0:
                subg.setdefault(pred, []).append((node, int(edge_type)))
    # A materialized cone is only a valid fixed-cut candidate if the traversal
    # actually reaches each intended boundary leaf where the replay uses it.
    boundary = sorted(set(subg) - seen)
    non_cut_boundary = [n for n in boundary if n not in cut and n != 0]
    if non_cut_boundary:
        raise ValueError(
            f"Replay cone for root {root} escaped fixed cut {sorted(cut)} via non-cut boundary {non_cut_boundary[:12]}"
        )
    info = {
        "representation_source": "Gate1 replay AIG full-correspondence cone",
        "replay_cone_nodes": sorted(seen),
        "replay_cone_boundary": boundary,
        "replay_cone_boundary_matches_fixed_cut": set(boundary).issubset(cut | {0}),
        "n_pi": int(n_pi),
    }
    return subg, info


def run_student(raw19: np.ndarray, checkpoint: Path) -> dict[str, Any]:
    # Reuse the repository's canonical compatibility loader (the same loader
    # used by its validation entry points), rather than defining a second
    # model-loading path in this adapter.
    from validate.eval_prediction_accuracy import load_student_model

    model, ckpt = load_student_model(str(checkpoint), "cpu")
    cfg = ckpt.get("config", {})
    payload = ckpt.get("abc_inference_payload", {})
    input_dim = int(payload.get("input_dim", cfg.get("input_dim", 19)))
    hidden = int(payload.get("shared_hidden_dim", cfg.get("shared_hidden_dim", 64)))
    num_experts = int(payload.get("num_experts", cfg.get("num_experts", 4)))
    temp = float(payload.get("gate_temperature", cfg.get("gate_temperature", 1.0)))
    group_dims = tuple(int(x) for x in payload.get("group_dims", [8, 6, 5]))
    if input_dim != 19 or group_dims != (8, 6, 5):
        raise ValueError(f"Unexpected Student schema input_dim={input_dim}, group_dims={group_dims}")
    x_mu = np.asarray(ckpt.get("x_mu", payload.get("input_mu")), dtype=np.float32).reshape(-1)
    x_inv = np.asarray(ckpt.get("x_inv_sigma", payload.get("input_inv_sigma")), dtype=np.float32).reshape(-1)
    y_mu = float(np.asarray(ckpt.get("y_mu", payload.get("output_mu"))).reshape(-1)[0])
    y_inv = float(np.asarray(ckpt.get("y_inv_sigma", payload.get("output_inv_sigma"))).reshape(-1)[0])
    if x_mu.size != 19 or x_inv.size != 19:
        raise ValueError(f"Checkpoint normalization dimensions are {x_mu.size}/{x_inv.size}, expected 19")
    raw19 = np.asarray(raw19, dtype=np.float32).reshape(1, 19)
    scaled = (raw19 - x_mu[None, :]) * x_inv[None, :]
    model.eval()
    with torch.inference_mode():
        out = model(torch.from_numpy(scaled)).prediction.detach().cpu().numpy().reshape(-1)
    raw_output = float(out[0])
    y_log = max(-10.0, min(10.0, raw_output / y_inv + y_mu))
    pred = float(math.expm1(y_log))
    return {
        "scaled_19": scaled.reshape(-1).astype(float).tolist(),
        "raw_model_output": raw_output,
        "inverse_standardized_log_delay": float(y_log),
        "predicted_raw_abc_delay": pred,
        "x_mu": x_mu.astype(float).tolist(),
        "x_inv_sigma": x_inv.astype(float).tolist(),
        "y_mu": y_mu,
        "y_inv_sigma": y_inv,
    }


def infer_one(record_path: Path, original_aig: Path, library_path: Path, checkpoint: Path) -> dict[str, Any]:
    record = json.loads(record_path.read_text(encoding="utf-8"))
    if "decisions" in record:
        if len(record["decisions"]) != 1:
            raise ValueError(f"Expected one decision in {record_path}")
        record = record["decisions"][0]
    feat_graph, max_var, n_pi, n_po, n_and = parse_aiger_ascii_binary(original_aig)
    lib = parse_library(library_path)
    # Prefer the exact materialized replay cone for a full-correspondence
    # candidate. Physical replacements are rebuilt from the rewrite library,
    # which avoids any mapper invocation and retains the requested cut.
    replay_aig = record_path.with_suffix(".aig")
    if record.get("installation_kind") == "NO_OP_FULL_CORRESPONDENCE" and replay_aig.exists():
        replay_graph, _, replay_pi, _, _ = parse_aiger_ascii_binary(replay_aig)
        subg, dag_info = extract_replay_cone_subgraph(replay_graph, record, replay_pi)
    else:
        subg, dag_info = materialize_candidate_subgraph(record, lib)
    extractor = CompleteCutFeatureExtractor(feat_graph, inverter_weight=1.5)
    full, names = extractor.extract_all(subg)
    if names != FEATURE_NAMES_25:
        raise ValueError(f"Canonical feature order mismatch: {names}")
    full_arr = np.asarray(full, dtype=np.float64)
    if not np.all(np.isfinite(full_arr)):
        raise ValueError(f"Non-finite canonical features for {record_path}: {full}")
    inference = run_student(full_arr[:19], checkpoint)
    result = {
        "candidate_record": record,
        "candidate_id": record_path.stem,
        "decision_root": int(record.get("target_root", record.get("root"))),
        "cut_leaves": [int(x) for x in record["cut_leaves"]],
        "subgraph_index": int(record["subgraph_index"]),
        "installation_kind": record.get("installation_kind"),
        "preserved_root_wrapper": int(record.get("preserved_root_wrapper", record.get("target_root", record.get("root")))),
        "original_aig": str(original_aig),
        "original_aig_sha256": sha256(original_aig),
        "aig_stats": {"max_var": max_var, "pi_count": n_pi, "po_count": n_po, "and_count": n_and},
        "feature_names_25": names,
        "raw_features_25": full_arr.tolist(),
        "continuous_features_19": full_arr[:19].tolist(),
        "laplacian_features_5": full_arr[19:24].tolist(),
        "wl_hash": int(full_arr[24]),
        "replacement_dag": {str(k): [[int(v), int(e)] for v, e in vals] for k, vals in sorted(subg.items())},
        "replacement_dag_info": dag_info,
        "checkpoint": str(checkpoint),
        "checkpoint_sha256": sha256(checkpoint),
        "model_payload": {
            "model_family": "student_group_fusion_soft_moe",
            "input_dim": 19,
            "group_dims": [8, 6, 5],
            "wl_hash_enters_student_forward": False,
        },
        "inference": inference,
    }
    return result


